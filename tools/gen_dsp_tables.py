"""Constant tables for firmware/lib/dsp.h and fx.h (from TastyWaves' tools/gen_engine_tables.py): everything that
needs exp / tan / tanh, computed here so the firmware stays integer only. Writes firmware/lib/dsp_tables.h.

    .venv/bin/python tools/gen_dsp_tables.py

DSP_CR (frames per control step) must match DSP_CR in firmware/lib/dsp.h (32 = 0.726 ms at 44.1 kHz).
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FS = 44100
CR = 32
Q30 = 1 << 30
Q28 = 1 << 28


def note_hz(n):
    return 440.0 * 2.0 ** ((n - 69) / 12.0)


def env_time(p):              # 0..127 -> 0.5 ms .. 10 s, exponential
    return 0.0005 * (20000.0 ** (p / 127.0))


def tables():
    t = {}
    t['DSP_INC_C9'] = ('uint32_t', [round(note_hz(120 + i) * 2 ** 32 / FS) for i in range(12)],
                       'phase steps of MIDI 120..131 (C9..B9) at 44.1 kHz; lower octaves shift right')
    t['DSP_FINE16'] = ('uint16_t', [round((2.0 ** (i / 3072.0) - 1.0) * 65536) for i in range(256)],
                       'fraction of a semitone (i / 256) -> (ratio - 1) * 65536')
    t['DSP_SVF_G'] = ('int32_t', [round(math.tan(math.pi * min(note_hz(n), 18000.0) / FS) * Q28) for n in range(136)],
                      'cutoff as a note number 0..135 -> g = tan(pi f / fs), Q28 (capped at 18 kHz)')
    t['DSP_SVF_2R'] = ('int32_t', [round(2 * 0.707 * ((0.015 / 0.707) ** (r / 127.0)) * Q28) for r in range(128)],
                       'resonance 0..127 -> 2R (damping), Q28: R = 0.707 (flat) .. 0.015 (near self-oscillation)')
    t['DSP_ENV_STEP'] = ('int32_t', [min(Q30, max(1, round(Q30 * CR / (env_time(p) * FS)))) for p in range(128)],
                         'time 0..127 (0.5 ms .. 10 s) -> Q30 step per control step for a full-scale ramp')
    t['DSP_ENV_COEF'] = ('int32_t', [round(Q30 * 10.0 ** (-3.0 * CR / (env_time(p) * FS))) for p in range(128)],
                         'time 0..127 -> Q30 multiplier per control step, -60 dB after the time')
    gl = [65536]
    for p in range(1, 128):
        T = 0.005 * (1000.0 ** ((p - 1) / 126.0))
        gl.append(max(1, round(65536 * (1.0 - math.exp(-CR * 4.0 / (T * FS))))))
    t['DSP_GLIDE_K'] = ('int32_t', gl, 'glide 0..127 -> one-pole coefficient per control step, Q16 (0 = instant; 127 = 5 s)')
    t['DSP_LFO_INC'] = ('uint32_t', [round(0.02 * (2000.0 ** (p / 127.0)) * 2 ** 32 * CR / FS) for p in range(128)],
                        'LFO rate 0..127 (0.02 .. 40 Hz) -> phase step per control step (>> 5: per sample)')
    t['DSP_DRIVE_G'] = ('int32_t', [round(256 * 16.0 ** (p / 127.0)) for p in range(128)], 'drive 0..127 -> gain 1..16, Q8')
    t['DSP_SOFTCLIP'] = ('int16_t', [round(16383 * math.tanh(i * 512 / 16384.0)) for i in range(258)],
                         'soft clip above the knee: (|x| - 16384) / 512 -> 16383 tanh(u / 16384), + 1 guard')
    t['DSP_SIN_T'] = ('int16_t', [round(32767 * math.sin(2 * math.pi * i / 256)) for i in range(257)],
                      'sine, a cycle in 256 steps + 1 guard, Q15')
    return t


def main():
    lines = ['/* generated by tools/gen_dsp_tables.py. Do not edit. */', '/* SPDX-License-Identifier: GPL-3.0-only */',
             '#pragma once', '#include <stdint.h>', '', f'#define DSP_TABLES_CR {CR}u            /* the control step these tables assume (frames) */', '']
    for name, (ty, vals, doc) in tables().items():
        lines += [f'/* {doc} */', f'static const {ty} {name}[{len(vals)}] = {{']
        for i in range(0, len(vals), 12):
            lines.append('    ' + ', '.join(f'{v}' + ('u' if ty.startswith('uint') and v > 0x7FFFFFFF else '') for v in vals[i:i + 12]) + ',')
        lines += ['};', '']
    out = ROOT / 'firmware' / 'lib' / 'dsp_tables.h'
    out.write_text('\n'.join(lines))
    print(f'{out.relative_to(ROOT)}: {sum(len(v[1]) for v in tables().values())} entries')


if __name__ == '__main__':
    main()
